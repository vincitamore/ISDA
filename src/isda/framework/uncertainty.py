"""
The measured imprecision of SCR / ND / RI, and its scope.

Three independent raters of one model family produced full seven-stratum
ledgers for the same 20 documents (corpus/rating/documents.json, protocol in
corpus/rating/protocol.md, results in corpus/exhibits/inter-rater.json). For
each document and stratum the spread of the compressed-size estimates is taken
in log2, since size estimates disagree multiplicatively, and propagated
through the ledger arithmetic by Monte Carlo (20,000 draws per document,
resampling both size and intensity tag).

The figures are the median, across the 19 documents whose rated ledgers
score, of the per-document standard deviation induced on each metric:

    SCR  +/- 0.26     ND  +/- 0.05     RI  +/- 0.07

The twentieth document is a 577-byte poem. Every rater's compressed sizes for
it total more than twice its length, the scorer refuses such a ledger, and so
the poem contributes to the size spread and the tag agreement but not to the
metric interval.

The per-stratum log2 SD of the size estimates runs 0.28-0.42: raters typically
disagree by a factor of about 1.2 either way.

Three limits travel with the figures:

- They measure reliability, not validity. Raters landing near each other says
  nothing about landing near the truth: K is uncomputable, there is no
  reference compressed size for any stratum of any text, and raters can agree
  and be wrong together.
- They are within one model family, so part of the agreement is that family's
  consistency with itself. Read the interval as a floor on disagreement.
- They are medians over a wide spread. Per-document SCR SD runs from 0.04 to
  1.81, so a document whose strata the raters read differently carries a much
  larger interval. The per-document figures are in the exhibit.
"""

from __future__ import annotations

# Source of record: corpus/exhibits/inter-rater.json, regenerated by
# `python scripts/rating-agreement.py`. A test holds these to the exhibit's
# medians rounded to two decimals.
MEASURED_SD: dict[str, float] = {"SCR": 0.26, "ND": 0.05, "RI": 0.07}

RATERS = 3
RATER_FAMILIES = ("grok-4.5-build",)
N_DOCUMENTS = 20
N_SCORED = 19


def precision_note() -> dict[str, object]:
    """The precision stamp `isda analyze` renders at the point of the numbers."""
    return {
        "status": "measured",
        "median_sd": dict(MEASURED_SD),
        "basis": (
            f"inter-rater study: {RATERS} independent model raters "
            f"x {N_DOCUMENTS} documents x 7 strata, log2 size spread propagated "
            "through the ledger arithmetic by Monte Carlo"
        ),
        "reliability_not_validity": (
            "raters landing near each other, not near the truth: K is "
            "uncomputable and raters can agree and be wrong together"
        ),
        "within_family": list(RATER_FAMILIES),
        "caveat": (
            f"median over the {N_SCORED} documents whose rated ledgers score; "
            "per-document SCR SD runs 0.04-1.81, "
            "so a document the raters read unevenly carries a far wider interval"
        ),
    }
